// Measures the mounted, idle compressor widget's height for every widget
// variant across viewport widths, and prints the CSS that reserves that
// height on the empty #compressor shell before JavaScript mounts it. Without
// the reservation everything below the widget jumps when it appears — a
// cumulative layout shift of 0.25–0.35 on mobile, enough to sink the
// Lighthouse performance score on every tool page.
//
// Run against a built preview (`npm run build && npx vite preview --port 4173`),
// then paste the output over the generated block in src/styles/widget.css:
//
//   node scripts/measure-widget-heights.mjs
//
// Re-run whenever the idle widget changes shape (new control, copy that wraps
// differently, spacing tokens). English pages are measured; other locales
// wrap a little differently, and a few pixels of residual shift is fine.
import { chromium } from 'playwright';

const BASE = process.env.PREVIEW_URL ?? 'http://localhost:4173';

// One representative page per variant, keyed by the CSS selector that
// identifies that variant on the empty shell (main.ts reads the same
// attributes to configure the widget, so they are always present).
const VARIANTS = [
  { sel: '#compressor[data-locked="true"]', path: '/compress-video-to-25mb/', note: 'locked preset' },
  { sel: '#compressor[data-tool="trim"]', path: '/trim-video/', note: 'trim tool' },
  // Trim pages also carry data-formats; excluded here so the trim rule wins.
  { sel: '#compressor[data-formats]:not([data-formats=""]):not([data-tool="trim"])', path: '/compress-video/', note: 'compress, format selector' },
  { sel: '#compressor[data-locked-format="mp3"], #compressor[data-locked-format="m4a"]', path: '/mp4-to-mp3/', note: 'audio extraction' },
  { sel: '#compressor[data-locked-format="gif"]', path: '/mp4-to-gif/', note: 'gif' },
  { sel: '#compressor', path: '/mov-to-mp4/', note: 'default: converter / unlocked without selector' },
];

const WIDTHS = [];
for (let w = 320; w <= 760; w += 10) WIDTHS.push(w);
WIDTHS.push(800, 900, 1024, 1280);

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const rows = [];
for (const v of VARIANTS) {
  await page.goto(BASE + v.path, { waitUntil: 'networkidle' });
  await page.waitForSelector('#compressor .dropzone');
  const heights = new Map();
  for (const w of WIDTHS) {
    await page.setViewportSize({ width: w, height: 900 });
    const h = await page.evaluate(() => {
      const el = document.getElementById('compressor');
      // The reservation itself must not be measured — read the content height.
      el.style.minHeight = '0';
      const h = el.getBoundingClientRect().height;
      el.style.minHeight = '';
      return h;
    });
    heights.set(w, Math.round(h));
  }
  rows.push({ ...v, heights });
}
await browser.close();

// Collapse consecutive widths with the same height into ranges. The widest
// range is the default rule; narrower ones become max-width media queries.
const ranges = (heights) => {
  const out = [];
  let start = WIDTHS[0];
  let prev = heights.get(WIDTHS[0]);
  for (let i = 1; i <= WIDTHS.length; i++) {
    const w = WIDTHS[i];
    const h = w === undefined ? null : heights.get(w);
    if (h !== prev) {
      out.push({ from: start, to: w === undefined ? Infinity : w - 1, h: prev });
      start = w;
      prev = h;
    }
  }
  return out;
};

let css = `/* ---- GENERATED by scripts/measure-widget-heights.mjs — do not edit by hand.
   Reserves the idle widget height on the empty shell so nothing below it
   shifts when JavaScript mounts the widget. Removed once mounted
   (data-mounted), so later states size freely. Later rules win, so the
   more specific variants come after the default. ---- */\n`;
// Default variant first, then the specific ones (cascade: later + more specific wins).
const ordered = [...rows].sort((a, b) => (a.sel === '#compressor' ? -1 : b.sel === '#compressor' ? 1 : 0));
for (const v of ordered) {
  const rs = ranges(v.heights);
  const widest = rs[rs.length - 1];
  const sels = v.sel.split(',').map((s) => s.trim() + ':not([data-mounted])').join(',\n');
  css += `\n/* ${v.note} (${v.path}) */\n${sels} { min-height: ${widest.h}px; }\n`;
  for (const r of rs.slice(0, -1).reverse()) {
    css += `@media (max-width: ${r.to}px) { ${sels.replace(/\n/g, ' ')} { min-height: ${r.h}px; } }\n`;
  }
}
css += `/* ---- END GENERATED ---- */\n`;
console.log(css);
