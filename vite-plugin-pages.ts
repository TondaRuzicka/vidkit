import { existsSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import type { Plugin } from 'vite';
import {
  DEFAULT_LOCALE,
  HREFLANG,
  LEGACY_EN_PATHS,
  LOCALES,
  PAGES,
  SITE_NAME,
  SITE_URL,
  pagePath,
  type Locale,
  type PageCategory,
  type PageDef,
} from './src/config';

const ROOT = resolve(import.meta.dirname);
const PARTIALS_DIR = join(ROOT, 'partials');
const TEMPLATES_DIR = join(ROOT, 'templates');
const CONTENT_DIR = join(ROOT, 'content');

function include(html: string): string {
  return html.replace(/<!--\s*@include\s+([\w-]+)\s*-->/g, (_, name: string) =>
    include(readFileSync(join(PARTIALS_DIR, `${name}.html`), 'utf8')),
  );
}

const readJson = (file: string): Record<string, string> =>
  JSON.parse(readFileSync(join(CONTENT_DIR, file), 'utf8'));

// Merged dictionary for a page+locale: site vars + shared (common) strings +
// page-specific strings. Page keys win over common, common over site vars.
function dictFor(pageId: string | null, locale: Locale): Record<string, string> {
  const dict: Record<string, string> = { SITE_NAME, SITE_URL };
  Object.assign(dict, readJson(`common.${locale}.json`));
  if (pageId) Object.assign(dict, readJson(`${pageId}.${locale}.json`));
  return dict;
}

// Resolve {{key}} placeholders from the dictionary. Runs twice so values that
// themselves contain placeholders (e.g. brand name inside a sentence) resolve.
function substitute(html: string, dict: Record<string, string>): string {
  const pass = (s: string) =>
    s.replace(/\{\{\s*([\w.]+)\s*\}\}/g, (m, key: string) =>
      key in dict ? dict[key]! : m,
    );
  return pass(pass(html));
}

function findPage(id: string): PageDef | undefined {
  return PAGES.find((p) => p.id === id);
}

// Share-card image for a page+locale. Generated by scripts/gen-og-images.mjs
// (run `npm run og:gen` after adding pages) and committed — the CI build
// can't render them. Path is relative to public/.
const ogImagePath = (page: PageDef, locale: Locale): string =>
  `/og/${page.id}-${locale}.png`;

const OG_LOCALE: Record<Locale, string> = {
  en: 'en_US',
  cs: 'cs_CZ',
  es: 'es_ES',
  pt: 'pt_BR',
  de: 'de_DE',
  tr: 'tr_TR',
  zh: 'zh_CN',
};

// <title>, description, canonical, og/twitter tags and hreflang alternates
// for a page. Values stay as {{placeholders}} — filled by substitute() later.
function metaBlock(page: PageDef, locale: Locale): string {
  const self = `${SITE_URL}${pagePath(page, locale)}`;
  const ogImage = `${SITE_URL}${ogImagePath(page, locale)}`;
  const alternates = page.locales
    .map(
      (l) =>
        `<link rel="alternate" hreflang="${HREFLANG[l]}" href="${SITE_URL}${pagePath(page, l)}" />`,
    )
    .join('\n');
  const xDefault = `<link rel="alternate" hreflang="x-default" href="${SITE_URL}${pagePath(page, DEFAULT_LOCALE)}" />`;
  return [
    `<title>{{meta.title}}</title>`,
    `<meta name="description" content="{{meta.description}}" />`,
    `<link rel="canonical" href="${self}" />`,
    `<meta property="og:title" content="{{og.title}}" />`,
    `<meta property="og:description" content="{{og.description}}" />`,
    `<meta property="og:url" content="${self}" />`,
    `<meta property="og:locale" content="${OG_LOCALE[locale]}" />`,
    `<meta property="og:image" content="${ogImage}" />`,
    `<meta property="og:image:width" content="1200" />`,
    `<meta property="og:image:height" content="630" />`,
    `<meta property="og:image:alt" content="{{og.title}}" />`,
    `<meta name="twitter:card" content="summary_large_image" />`,
    alternates,
    xDefault,
  ].join('\n');
}

// Full native language names, keyed by locale so adding a locale is a
// type-checked one-line edit (a missing entry fails the build).
const NATIVE_NAMES: Record<Locale, string> = {
  en: 'English',
  cs: 'Čeština',
  es: 'Español',
  pt: 'Português',
  de: 'Deutsch',
  tr: 'Türkçe',
  zh: '简体中文',
};

// Language switcher: a native <details> dropdown that works fully with
// JavaScript disabled. The <summary> shows a globe + the current locale code;
// the menu lists every available locale for this page by its native name.
// langbanner.ts adds optional outside-click / Escape closing on top of this.
function langSwitch(page: PageDef, current: Locale): string {
  const globe =
    '<svg class="lang-menu__globe" viewBox="0 0 24 24" width="16" height="16" fill="none" aria-hidden="true"><circle cx="12" cy="12" r="9" stroke="currentColor" stroke-width="1.6"/><path d="M3 12h18M12 3c2.4 2.6 2.4 15.4 0 18M12 3c-2.4 2.6-2.4 15.4 0 18" stroke="currentColor" stroke-width="1.6"/></svg>';
  const chevron =
    '<svg class="lang-menu__chevron" viewBox="0 0 24 24" width="14" height="14" fill="none" aria-hidden="true"><path d="m6 9 6 6 6-6" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/></svg>';
  const items = page.locales
    .map((l) => {
      const href = pagePath(page, l);
      const aria = l === current ? ' aria-current="true"' : '';
      return `<li><a hreflang="${HREFLANG[l]}" lang="${HREFLANG[l]}" href="${href}"${aria}>${NATIVE_NAMES[l]}</a></li>`;
    })
    .join('');
  return `<details class="lang-menu"><summary aria-label="Language — ${NATIVE_NAMES[current]}">${globe}<span class="lang-menu__code">${current.toUpperCase()}</span>${chevron}</summary><ul>${items}</ul></details>`;
}

// --- Link mesh: hub index, related tools, breadcrumbs --------------------
// All three are generated from the PAGES registry rather than hand-written
// lists, so adding a page links it from its hub and its neighbours with no
// list to update — which is what keeps the crawl reachable as the site grows.

const CATEGORY_ORDER: PageCategory[] = [
  'compress',
  'convert',
  'audio',
  'reference',
];

/**
 * A page's short link text. Reuses the labels the footer and homepage already
 * ship in every locale — their key prefix varies by cluster, hence the chain.
 * Throws rather than emitting a blank link: a silent gap here would be an
 * unlabelled link on every page in the site.
 */
function labelFor(pageId: string, dict: Record<string, string>): string {
  for (const prefix of ['convert', 'audio', 'footer', 'nav', 'hub']) {
    const v = dict[`${prefix}.${pageId}`];
    if (v) return v;
  }
  throw new Error(
    `No link label for page '${pageId}'. Add convert.${pageId} (or footer.${pageId}) to content/common.*.json.`,
  );
}

function urlFor(pageId: string, dict: Record<string, string>): string {
  const v = dict[`url.${pageId}`];
  if (!v) {
    throw new Error(
      `No url.${pageId} in content/common.*.json — every linked page needs one.`,
    );
  }
  return v;
}

const linkItem = (p: PageDef, dict: Record<string, string>): string =>
  `<li><a href="${urlFor(p.id, dict)}">${labelFor(p.id, dict)}</a></li>`;

/** Tool pages available in this locale, hubs and home excluded. */
const toolsIn = (locale: Locale): PageDef[] =>
  PAGES.filter(
    (p) =>
      p.category &&
      p.category !== 'hub' &&
      (p.locales as readonly string[]).includes(locale),
  );

/**
 * Full tool index for a hub page. `scope` is 'all' or a single category,
 * read from the page's own `hub.scope` key. Group headings come from
 * `hubgroup.<category>`.
 */
function toolIndex(scope: string, locale: Locale, dict: Record<string, string>): string {
  const cats = scope === 'all' ? CATEGORY_ORDER : [scope as PageCategory];
  return cats
    .map((cat) => {
      const items = toolsIn(locale).filter((p) => p.category === cat);
      if (items.length === 0) return '';
      const heading = dict[`hubgroup.${cat}`] ?? cat;
      return [
        `<section class="section">`,
        `<div class="container">`,
        `<div class="section-head"><h2>${heading}</h2></div>`,
        `<ul class="convert-links">`,
        items.map((p) => linkItem(p, dict)).join('\n'),
        `</ul>`,
        `</div>`,
        `</section>`,
      ].join('\n');
    })
    .join('\n');
}

/** Slug words that carry meaning, used to score how related two tools are. */
const tokensOf = (p: PageDef): string[] =>
  p.slugs.en.split('-').filter((t) => t && t !== 'to' && t !== 'from');

/**
 * Up to six sibling tools, most related first. A shared *input* format counts
 * double, because that's what the visitor actually has in hand: someone on
 * MOV→MP4 is far likelier to want MOV→MP3 than yet another X→MP4. Sharing the
 * output format alone (the near-universal 'mp4') is the weakest signal, so a
 * same-category tiebreak keeps those groupings sensible.
 */
function relatedBlock(page: PageDef, locale: Locale, dict: Record<string, string>): string {
  if (!page.category || page.category === 'hub') return '';
  const mine = tokensOf(page);
  const myInput = mine[0];
  const mineSet = new Set(mine);
  const scored = toolsIn(locale)
    .filter((p) => p.id !== page.id)
    .map((p) => {
      const theirs = tokensOf(p);
      const shared = theirs.filter((t) => mineSet.has(t)).length;
      const sameInput = myInput && theirs[0] === myInput ? 1 : 0;
      return {
        page: p,
        score: shared + sameInput + (p.category === page.category ? 0.5 : 0),
      };
    })
    .filter((c) => c.score > 0)
    .sort((a, b) => b.score - a.score);
  const picks = scored.slice(0, 6).map((c) => c.page);
  if (picks.length === 0) return '';

  const hubId = page.category === 'convert' ? 'convertvideo' : 'videotools';
  const hub = findPage(hubId);
  const showHub = hub && (hub.locales as readonly string[]).includes(locale);
  // Labelled from the hub it points at, so convert pages read "Convert video"
  // and everything else "All video tools" — never a link that misnames itself.
  const allLink = showHub
    ? `<p class="related-all"><a href="${urlFor(hubId, dict)}">${labelFor(hubId, dict)}</a></p>`
    : '';

  return [
    `<section class="section section--tint">`,
    `<div class="container">`,
    `<div class="section-head"><h2>${dict['related.heading'] ?? 'Related tools'}</h2></div>`,
    `<ul class="convert-links">`,
    picks.map((p) => linkItem(p, dict)).join('\n'),
    `</ul>`,
    allLink,
    `</div>`,
    `</section>`,
  ].join('\n');
}

/**
 * Home → hub → page. Emitted only for the default locale: the hubs are
 * English-only, and a trail that switches language mid-way is worse than none.
 */
function breadcrumbJsonLd(
  page: PageDef,
  locale: Locale,
  dict: Record<string, string>,
): string | null {
  if (locale !== DEFAULT_LOCALE) return null;
  if (!page.category) return null;

  const trail: { name: string; path: string }[] = [
    { name: SITE_NAME, path: pagePath(findPage('home')!, locale) },
  ];
  if (page.category !== 'hub') {
    const hubId = page.category === 'convert' ? 'convertvideo' : 'videotools';
    const hub = findPage(hubId);
    if (hub && (hub.locales as readonly string[]).includes(locale)) {
      trail.push({ name: labelFor(hubId, dict), path: pagePath(hub, locale) });
    }
  }
  trail.push({ name: labelFor(page.id, dict), path: pagePath(page, locale) });

  const ld = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: trail.map((t, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: stripTags(t.name),
      item: `${SITE_URL}${t.path}`,
    })),
  };
  return `<script type="application/ld+json">${JSON.stringify(ld)}</script>`;
}

const ENTITIES: Record<string, string> = {
  '&nbsp;': ' ',
  '&amp;': '&',
  '&lt;': '<',
  '&gt;': '>',
  '&quot;': '"',
  '&#39;': "'",
};

// Structured data carries plain text, not markup: labels like "Compress to
// 25&nbsp;MB" must reach JSON-LD as real characters, or the entity shows up
// verbatim in a rich result.
const stripTags = (s: string) =>
  s
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;|&amp;|&lt;|&gt;|&quot;|&#39;/g, (e) => ENTITIES[e]!)
    .replace(/\s+/g, ' ')
    .trim();

// Builds FAQPage JSON-LD from the visible <details class="faq-item"> markup,
// so the structured data can never drift from what the page shows.
function faqJsonLd(html: string): string | null {
  const items = [
    ...html.matchAll(
      /<details class="faq-item">\s*<summary>([\s\S]*?)<\/summary>([\s\S]*?)<\/details>/g,
    ),
  ];
  if (items.length === 0) return null;
  const ld = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: items.map(([, q, a]) => ({
      '@type': 'Question',
      name: stripTags(q!),
      acceptedAnswer: { '@type': 'Answer', text: stripTags(a!) },
    })),
  };
  return `<script type="application/ld+json">${JSON.stringify(ld)}</script>`;
}

// Full transform for one entry HTML file. Self-describing via directives:
//   <!-- @meta <pageId> <locale> -->   head: title/meta/canonical/hreflang
//   <!-- @render <pageId> <locale> --> body: the page template
//   <!-- @langswitch -->               language switcher (in shared header)
// Legacy pages carry no directives: they resolve common.<default> strings only
// so their shared partials still fill in, and get no switcher.
function render(rawHtml: string): string {
  let html = include(rawHtml);

  const ctx = html.match(/<!--\s*@(?:meta|render)\s+([\w-]+)\s+([\w-]+)\s*-->/);
  const pageId = ctx ? ctx[1]! : null;
  const locale: Locale =
    ctx && (LOCALES as readonly string[]).includes(ctx[2]!)
      ? (ctx[2] as Locale)
      : DEFAULT_LOCALE;
  const page = pageId ? findPage(pageId) : undefined;

  html = html.replace(/<!--\s*@meta\s+[\w-]+\s+[\w-]+\s*-->/g, () =>
    page ? metaBlock(page, locale) : '',
  );
  html = html.replace(/<!--\s*@render\s+[\w-]+\s+[\w-]+\s*-->/g, () =>
    page ? readFileSync(join(TEMPLATES_DIR, `${page.template}.html`), 'utf8') : '',
  );
  html = html.replace(/<!--\s*@langswitch\s*-->/g, () =>
    page ? langSwitch(page, locale) : '',
  );

  const dict = dictFor(pageId, locale);

  // Link-mesh directives resolve before substitute() so the labels and URLs
  // they pull from the dictionary still get their own {{SITE_NAME}} pass.
  html = html.replace(/<!--\s*@toolindex\s*-->/g, () =>
    page ? toolIndex(dict['hub.scope'] ?? 'all', locale, dict) : '',
  );
  html = html.replace(/<!--\s*@related\s*-->/g, () =>
    page ? relatedBlock(page, locale, dict) : '',
  );

  html = substitute(html, dict);

  const ld = faqJsonLd(html);
  if (ld) html = html.replace('</head>', `${ld}\n</head>`);
  const crumbs = page ? breadcrumbJsonLd(page, locale, dict) : null;
  if (crumbs) html = html.replace('</head>', `${crumbs}\n</head>`);
  return html;
}

const allPaths = (): string[] => [
  ...PAGES.flatMap((p) => p.locales.map((l) => pagePath(p, l))),
  ...LEGACY_EN_PATHS,
];

const sitemap = () =>
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${allPaths()
    .map((p) => `  <url><loc>${SITE_URL}${p}</loc></url>`)
    .join('\n')}\n</urlset>\n`;

const robots = () =>
  `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`;

export default function pages(): Plugin {
  return {
    name: 'vidkit-pages',
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'sitemap.xml', source: sitemap() });
      this.emitFile({ type: 'asset', fileName: 'robots.txt', source: robots() });
      for (const page of PAGES) {
        for (const locale of page.locales) {
          const img = join(ROOT, 'public', ogImagePath(page, locale));
          if (!existsSync(img)) {
            this.warn(
              `Missing share card ${ogImagePath(page, locale)} — run \`npm run og:gen\` and commit it.`,
            );
          }
        }
      }
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (req.url === '/sitemap.xml') {
          res.setHeader('Content-Type', 'application/xml');
          res.end(sitemap());
        } else if (req.url === '/robots.txt') {
          res.setHeader('Content-Type', 'text/plain');
          res.end(robots());
        } else next();
      });
    },
    transformIndexHtml: {
      order: 'pre',
      handler(html) {
        return render(html);
      },
    },
    handleHotUpdate({ file, server }) {
      if (
        file.startsWith(PARTIALS_DIR) ||
        file.startsWith(TEMPLATES_DIR) ||
        file.startsWith(CONTENT_DIR)
      ) {
        server.ws.send({ type: 'full-reload' });
      }
    },
  };
}
